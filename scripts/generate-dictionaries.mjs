import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dictionariesDirectory = join(root, "dictionaries");
const generatedDirectory = join(
  root,
  "packages",
  "profanity-kit",
  "src",
  "generated"
);

const compareCodePoints = (left, right) => {
  const leftPoints = Array.from(left, (character) => character.codePointAt(0));
  const rightPoints = Array.from(right, (character) =>
    character.codePointAt(0)
  );
  for (
    let index = 0;
    index < Math.min(leftPoints.length, rightPoints.length);
    index += 1
  ) {
    if (leftPoints[index] !== rightPoints[index]) {
      return leftPoints[index] - rightPoints[index];
    }
  }
  return leftPoints.length - rightPoints.length;
};

const readDictionary = (code) => {
  const directory = join(dictionariesDirectory, code);
  const metadata = JSON.parse(
    readFileSync(join(directory, "metadata.json"), "utf8")
  );
  if (metadata.code !== code || !/^\d+\.\d+\.\d+$/.test(metadata.version)) {
    throw new Error(`Invalid metadata for ${code}`);
  }
  const words = readFileSync(join(directory, "words.txt"), "utf8")
    .split(/\r?\n/)
    .map((word) => word.trim())
    .filter(Boolean);
  const normalized = words.map((word, index) => {
    if (word !== word.normalize("NFC")) {
      throw new Error(`${code} word ${index + 1} is not NFC-normalized`);
    }
    if (word !== word.toLowerCase()) {
      throw new Error(`${code} word ${index + 1} is not lowercase`);
    }
    if (/\s/.test(word) || /[^\p{L}\p{M}\p{N}]/u.test(word)) {
      throw new Error(`${code} word ${index + 1} is not a single Unicode word`);
    }
    return word;
  });
  const unique = new Set(normalized);
  if (unique.size !== normalized.length) {
    throw new Error(`${code} dictionary contains duplicate words`);
  }
  return { metadata, words: normalized.sort(compareCodePoints) };
};

const render = ({ metadata, words }) =>
  [
    "// Generated by scripts/generate-dictionaries.mjs; do not edit manually.",
    "export const words = Object.freeze([",
    ...words.map((word) => `  ${JSON.stringify(word)},`),
    "] as const);",
    `export const version = ${JSON.stringify(metadata.version)};`,
    "",
  ].join("\n");

const check = process.argv.includes("--check");
const codes = readdirSync(dictionariesDirectory, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort(compareCodePoints);
const mismatches = [];

for (const code of codes) {
  const dictionary = readDictionary(code);
  const outputPath = join(generatedDirectory, `${code}.ts`);
  const output = render(dictionary);
  if (check) {
    if (readFileSync(outputPath, "utf8") !== output)
      mismatches.push(outputPath);
  } else {
    writeFileSync(outputPath, output);
  }
}

if (mismatches.length > 0) {
  throw new Error(
    `Generated dictionaries are stale:\n- ${mismatches.join("\n- ")}`
  );
}
